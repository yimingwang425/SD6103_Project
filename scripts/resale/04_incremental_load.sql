-- ============================================================
-- SD6103 Project: Incremental Loading of Resale Data
--
-- Loads 5 staging CSVs into hdb_flat + resale_transaction via
-- a TEMP TABLE + JOIN approach:
--   1. COPY staging CSV into a temp table
--   2. INSERT INTO hdb_flat  ... SELECT DISTINCT ... JOIN hdb_block
--      (ON CONFLICT DO NOTHING for deduplication)
--   3. INSERT INTO resale_transaction ... SELECT ... JOIN hdb_block + hdb_flat
--   4. Report unmatched rows, DROP temp table
--
-- Prerequisites:
--   - Run 03_create_tables.sql first
--   - Staging CSVs in data/clean_data/resale/incremental/
--     (generated by 01_clean_resale.py + 02_split_resale.py)
--
-- Usage:
--   cd <project_root>/data/clean_data/resale/incremental
--   psql -U postgres -d sd6103_project
--   Then paste each section below, or run the whole file.
--
-- File loading order (chronological):
--   File 1: 1990-1999
--   File 2: 2000-2012
--   File 3: 2012-2014
--   File 4: 2015-2016
--   File 5: 2017-onwards
-- ============================================================

-- Defensive: prevent duplicate rows on re-run
TRUNCATE resale_transaction, hdb_flat CASCADE;


-- ============ LOAD FILE 1 (1990-1999) ============
CREATE TEMP TABLE staging (
    blk_no VARCHAR(10), street VARCHAR(200), flat_type VARCHAR(20),
    storey_min INTEGER, storey_max INTEGER,
    floor_area_sqm NUMERIC(6,1), flat_model VARCHAR(30),
    transaction_year INTEGER, transaction_month INTEGER,
    remaining_lease_years INTEGER, resale_price INTEGER
);

\copy staging FROM 'file1_staging.csv' WITH (FORMAT csv, HEADER true);

INSERT INTO hdb_flat (block_id, flat_type, storey_min, storey_max, floor_area_sqm, flat_model)
SELECT DISTINCT b.block_id, s.flat_type, s.storey_min, s.storey_max,
       s.floor_area_sqm, s.flat_model
FROM   staging s
JOIN   hdb_block b ON s.blk_no = b.block_number AND s.street = b.street
ON CONFLICT DO NOTHING;

INSERT INTO resale_transaction (flat_id, transaction_year, transaction_month,
                                remaining_lease_years, resale_price)
SELECT f.flat_id, s.transaction_year, s.transaction_month,
       s.remaining_lease_years, s.resale_price
FROM   staging s
JOIN   hdb_block b ON s.blk_no = b.block_number AND s.street = b.street
JOIN   hdb_flat f  ON b.block_id = f.block_id
                  AND s.flat_type = f.flat_type
                  AND s.storey_min = f.storey_min
                  AND s.storey_max = f.storey_max
                  AND s.floor_area_sqm = f.floor_area_sqm
                  AND s.flat_model = f.flat_model;

SELECT 'File 1 unmatched' AS check,
       COUNT(*) AS unmatched_rows
FROM   staging s
LEFT JOIN hdb_block b ON s.blk_no = b.block_number AND s.street = b.street
WHERE  b.block_id IS NULL;

DROP TABLE staging;

SELECT 'After File 1' AS stage,
       (SELECT COUNT(*) FROM hdb_flat) AS total_flats,
       (SELECT COUNT(*) FROM resale_transaction) AS total_transactions;


